def tr(key: str, lang: str = "ru") -> str:
    """Translate a key to the given language. Falls back to Russian, then to key itself."""
    return TRANSLATIONS.get(lang, TRANSLATIONS["ru"]).get(key, TRANSLATIONS["ru"].get(key, key))


def get_js_translations(lang: str = "ru") -> dict:
    """Return a subset of translations for use in JavaScript."""
    src = TRANSLATIONS.get(lang, TRANSLATIONS["ru"])
    return {k: src.get(k, TRANSLATIONS["ru"].get(k, k)) for k in JS_KEYS}
